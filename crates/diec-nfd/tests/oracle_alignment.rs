/// Corrupted RNC streams must fail verification rather than panic or
/// mis-detect (truncated stream, bad packed CRC, bad raw CRC).
#[test]
fn rnc_corrupt_inputs_rejected() {
    let good = corpus("minimal.rnc1");
    for cut in [12usize, 18, 20, 25, 29] {
        let d = &good[..cut];
        let ft = sniff_ft(d);
        let out = scan(d, ft, oracle_opts());
        assert!(
            !out.iter().any(|r| r.record_name == "RNC"),
            "cut {cut}: {out:?}"
        );
    }
    // Bad packed CRC at offset 14.
    let mut bad = good.clone();
    bad[14] ^= 0xff;
    let out = scan(&bad, sniff_ft(&bad), oracle_opts());
    assert!(!out.iter().any(|r| r.record_name == "RNC"), "{out:?}");
    // Bad raw CRC at offset 12 (valid packed CRC -> verification path).
    let mut bad = good.clone();
    bad[12] ^= 0xff;
    let out = scan(&bad, sniff_ft(&bad), oracle_opts());
    assert!(!out.iter().any(|r| r.record_name == "RNC"), "{out:?}");
}

