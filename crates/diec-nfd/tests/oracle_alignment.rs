/// Locked stream whose key is underdetermined (single literal run, key
/// not in `KNOWN_KEYS`): upstream leaves the output encrypted, the CRC
/// verify fails, and no RNC record is emitted. Truncated old/encrypted
/// streams and CRC corruption must likewise fail closed.
#[test]
fn rnc_encrypted_unrecoverable_and_corrupt_rejected() {
    let out = run("rnc1-enc-badkey.rnc1");
    assert!(!out.iter().any(|r| r.record_name == "RNC"), "{out:?}");

    for name in ["rnc1-old.rnc1", "rnc2-old.rnc2", "rnc1-enc-unique.rnc1"] {
        let good = corpus(name);
        for cut in [12usize, good.len() - 1, good.len() - 2] {
            let d = &good[..cut];
            let out = scan(d, sniff_ft(d), oracle_opts());
            assert!(
                !out.iter().any(|r| r.record_name == "RNC"),
                "{name} cut {cut}: {out:?}"
            );
        }
    }
    // Bad raw CRC on the recoverable encrypted stream.
    let mut bad = corpus("rnc1-enc-known.rnc1");
    bad[12] ^= 0xff;
    let out = scan(&bad, sniff_ft(&bad), oracle_opts());
    assert!(!out.iter().any(|r| r.record_name == "RNC"), "{out:?}");
}

/// Upstream `nEntryPointSection` resolves the EP virtual address against
/// the section memory map in reverse order — overlapping VAs resolve to
/// the LAST section (Phase 26 fix; previously file-offset extents were
/// used, which resolves to the first section).
#[test]
fn ep_section_index_uses_va_space() {
    let d = corpus("fsg-v100-two.unpacked.exe");
    let info = diec_nfd::pe::collect(&d).expect("pe collect");
    // Both sections start at VA 0x1000; EP RVA 0x1000 resolves to sec 1.
    assert_eq!(info.entrypoint_section_index(), 1);
}

/// Section names keep their raw case (upstream `SECTION_RECORD.sName`)
/// so section-name scan records match case-sensitively: `.enigma1` →
/// Enigma Virtual Box, `.bxpck` → BoxedApp Packer (Phase 28 fix;
/// previously the parser uppercased names and the CRC scan missed).
#[test]
fn section_name_detects_are_case_sensitive() {
    let out = run("enigmavb-minimal.exe");
    assert!(has(&out, "Protector", "Enigma Virtual Box"), "{out:?}");
    let out = run("boxedapp-minimal.exe");
    assert!(has(&out, "Protector", "BoxedApp Packer"), "{out:?}");

    // Raw-case names are preserved for downstream compares.
    let d = corpus("enigmavb-minimal.exe");
    let info = diec_nfd::pe::collect(&d).expect("pe collect");
    assert!(info.section_names.iter().any(|n| n == ".enigma1"));
    assert!(!info.section_names.iter().any(|n| n == ".ENIGMA1"));
}

/// Phase 46 — `handle_Microsoftoffice`: a `docProps/app.xml` member
/// (0 < unc_size <= 0x4000) emits the Office flavor format record from
/// `<Application>`; `<AppVersion>` carries the version. Oracle-verified
/// over synthetic zips (tools/gen_p46_corpus.py).
#[test]
fn zip_app_xml_emits_office_format_records() {
    // Microsoft Office Word -> WORD record with AppVersion.
    let out = run("office-docx.zip");
    assert!(
        out.iter().any(|r| r.record_type == "Format"
            && r.record_name == "Microsoft Office Word"
            && r.version == "16.0000"),
        "{out:?}"
    );
    // Microsoft Excel -> EXCEL record.
    let out = run("office-xlsx.zip");
    assert!(
        out.iter().any(|r| r.record_type == "Format"
            && r.record_name == "Microsoft Excel"
            && r.version == "12.0"),
        "{out:?}"
    );
    // SheetJS -> EXCEL record with sInfo "SheetJS" (empty version).
    let out = run("office-sheetjs.zip");
    assert!(
        out.iter().any(|r| r.record_type == "Format"
            && r.record_name == "Microsoft Excel"
            && r.version.is_empty()
            && r.info == "SheetJS"),
        "{out:?}"
    );
    // Unknown Application -> bare MICROSOFTOFFICE with AppVersion.
    let out = run("office-plain.zip");
    assert!(
        out.iter().any(|r| r.record_type == "Format"
            && r.record_name == "Microsoft Office"
            && r.version == "9.9"),
        "{out:?}"
    );
    // Missing <Application> still emits MICROSOFTOFFICE + AppVersion.
    let out = run("office-noapp.zip");
    assert!(
        out.iter().any(|r| r.record_type == "Format"
            && r.record_name == "Microsoft Office"
            && r.version == "7.7"),
        "{out:?}"
    );
    // Stored (method 0) members decompress the same.
    let out = run("office-stored.zip");
    assert!(
        out.iter()
            .any(|r| r.record_type == "Format" && r.record_name == "Microsoft Office Word"),
        "{out:?}"
    );
}

